package com.khaleel.newleaf

import com.khaleel.newleaf.data.*
import java.io.File
import java.time.Instant
import java.time.ZoneId
import java.util.Base64
import java.util.zip.ZipInputStream
import org.junit.Assert.*
import org.junit.Test

/** Generates inspectable fictional samples with the same exporters used by the app. */
class ReleaseSamplesTest {
    @Test fun exportAndRestoreFictionalSampleWithAttachment() {
        val time=Instant.parse("2026-09-28T12:30:00Z")
        fun at(e:Entry)=EventTimes.at(e,time,ZoneId.of("UTC"))
        val meal=at(Entry(id="sample-meal",kind=EntryKind.MEAL,name="Example lunch",notes="Fictional data for export review.",componentIds=listOf("sample-food","sample-water"),photoPaths=listOf("sample-photo.png")))
        val food=at(Entry(id="sample-food",kind=EntryKind.FOOD,name="Example food",mealId=meal.id,quantity=150.0,unit="g",massGrams=150.0,portionEvidence="measured",nutrients=mapOf("energy_kcal" to 300.0,"protein_g" to 20.0,"sodium_mg" to null),notes="=SUM(1,2)\nA comma, and Unicode: café"))
        val water=at(Entry(id="sample-water",kind=EntryKind.DRINK,name="Water",mealId=meal.id,quantity=16.0,unit="fl oz",volumeMl=473.176473,countsAsWater=true,nutrients=mapOf("energy_kcal" to 0.0)))
        val weight=at(Entry(id="sample-weight",kind=EntryKind.WEIGHT,name="Example weigh-in",quantity=180.0,unit="lb",weightKg=81.6466266))
        val activity=at(Entry(id="sample-walk",kind=EntryKind.ACTIVITY,name="Example walk",distanceMeters=1609.344,durationSeconds=1200))
        val steps=at(Entry(id="sample-steps",kind=EntryKind.STEPS,name="Daily steps",steps=6500))
        val feeling=EventTimes.at(Entry(id="sample-feeling",kind=EntryKind.CHECKIN,name="After lunch",mealId=meal.id,tags=listOf("satisfied"),ratings=mapOf("energy" to 4)),time.plusSeconds(3600),ZoneId.of("UTC"))
        val journal=Journal(entries=listOf(meal,food,water,weight,activity,steps,feeling),settings=AppSettings(gatewayToken="NEVER-EXPORT-FICTIONAL-SECRET"),drafts=mapOf("editor" to "PRIVATE-DRAFT"))
        val photo=Base64.getDecoder().decode("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jZ3cAAAAASUVORK5CYII=")
        val reader=PhotoReader { path->require(path=="sample-photo.png");photo }
        val json=JournalExports.json(journal)
        val markdown=JournalExports.markdown(journal)
        val csv=JournalExports.csvZip(journal,ExportOptions(includePhotos=true),reader)
        val backup=JournalExports.backup(journal,reader)
        val preview=JournalExports.previewRestore(backup)
        assertEquals(7,preview.journal.entries.size)
        assertEquals(1,preview.attachments.size)
        assertArrayEquals(photo,preview.attachments.single().bytes)
        assertFalse(json.contains("NEVER-EXPORT"))
        assertFalse(json.contains("PRIVATE-DRAFT"))
        assertTrue(markdown.contains("Example lunch"))
        val zipEntries=mutableMapOf<String,String>()
        ZipInputStream(csv.inputStream()).use { z->var e=z.nextEntry;while(e!=null){zipEntries[e.name]=z.readBytes().toString(Charsets.UTF_8);e=z.nextEntry} }
        assertTrue(zipEntries.containsKey("journal.json"))
        assertTrue(zipEntries.values.any { it.contains("'=SUM(1,2)") })
        val summary=Summaries.day(preview.journal.entries,"2026-09-28")
        assertEquals(300.0,summary.nutrients["energy_kcal"]!!.knownSum!!,0.0)
        assertEquals(6500L,summary.steps)
        val working=File(System.getProperty("user.dir"))
        val root=if(File(working,"docs").isDirectory)working else working.parentFile
        require(File(root,"settings.gradle.kts").isFile)
        val out=File(root,"releases/samples").apply { mkdirs() }
        File(out,"example-journal.json").writeText(json)
        File(out,"example-report.md").writeText(markdown)
        File(out,"example-spreadsheets.zip").writeBytes(csv)
        File(out,"example-backup.zip").writeBytes(backup)
        File(out,"README.md").writeText("# Fictional Newleaf export samples\n\nGenerated by the real app exporters during ReleaseSamplesTest. Nutrition values are fixtures, not food recommendations. The attachment is a one-pixel test image. No owner journal data or credentials are included.\n")
    }
}
